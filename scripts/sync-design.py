#!/usr/bin/env python3
"""Generate native platform palettes/assets from the shared Deckivo design."""
import json
from pathlib import Path
import shutil

ROOT=Path(__file__).resolve().parents[1]
DESIGN=ROOT/'design-system'
tokens=json.loads((DESIGN/'tokens.json').read_text())
c=tokens['colors']
desktop=ROOT/'desktop/linux'
style=(DESIGN/'desktop.qss.in').read_text()
for name,value in c.items():style=style.replace('${'+name+'}',value)
assert '${' not in style
(desktop/'ui_theme.py').write_text('# Generated by scripts/sync-design.py; edit design-system instead.\nSTYLE = '+repr(style)+'\n')
for name in ('play-space.svg',):
    shutil.copy2(DESIGN/'assets'/name,desktop/'assets'/name)
shutil.copytree(DESIGN/'assets/fonts',desktop/'assets/fonts',dirs_exist_ok=True)
res=ROOT/'android/app/src/main/res'
(res/'drawable-nodpi').mkdir(exist_ok=True)

(res/'font').mkdir(exist_ok=True)
shutil.copy2(DESIGN/'assets/fonts/IBMPlexSans.ttf',res/'font/ibm_plex_sans_variable.ttf')
font_xml=('''<font-family xmlns:android="http://schemas.android.com/apk/res/android">
<font android:font="@font/ibm_plex_sans_variable" android:fontWeight="400" android:fontStyle="normal" android:fontVariationSettings="'wght' 400"/>
<font android:font="@font/ibm_plex_sans_variable" android:fontWeight="600" android:fontStyle="normal" android:fontVariationSettings="'wght' 600"/>
</font-family>''')
(res/'font-v28').mkdir(exist_ok=True)
(res/'font-v28/ibm_plex_sans.xml').write_text(font_xml)
import re
(res/'font/ibm_plex_sans.xml').write_text(re.sub(r' android:fontVariationSettings="[^"]+"','',font_xml))
mapping={'accent':'accent','deckivo_bg':'background',
 'deckivo_surface':'surface','deckivo_border':'border','deckivo_text':'text',
 'deckivo_muted':'muted','deckivo_ink':'ink','deckivo_warning':'warning',
 'deckivo_rail':'rail','stream_text':'text'}
entries={key:c[value] for key,value in mapping.items()}
entries.update(stream_background='#000000',stream_overlay_background='#EB1A1E24',
               control_primary='#22DAF975',control_pressed='#88DAF975',item_delete_background='#9E3146')
(res/'values/colors.xml').write_text('<resources>\n'+''.join(f'    <color name="{k}">{v}</color>\n' for k,v in entries.items())+'</resources>\n')
print('Shared Deckivo colors, font and own screen illustration synchronized.')
