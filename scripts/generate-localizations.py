#!/usr/bin/env python3
"""Compile reviewed catalog sources into native Android resources and the static site."""
from pathlib import Path
import json, re, html
ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = {'en':'English','ru':'Русский','uk':'Українська','pl':'Polski','de':'Deutsch','fr':'Français','es':'Español','it':'Italiano','pt':'Português','tr':'Türkçe','zh':'简体中文','ja':'日本語','ko':'한국어','ar':'العربية','hi':'हिन्दी','id':'Bahasa Indonesia'}
base = json.loads((ROOT/'localization/en.json').read_text())
extra = json.loads((ROOT/'localization/native-extra.json').read_text())
all_catalogs = {}
used=set()
for source in (ROOT/'android/app/src/main').rglob('*'):
    if 'cpp' in source.relative_to(ROOT/'android/app/src/main').parts or source.suffix not in ('.kt','.java','.xml') or source.name=='deckivo_strings.xml':continue
    text=source.read_text()
    used.update(re.findall(r'R\.string\.(\w+)|@string/(\w+)',text))
used={name for pair in used for name in pair if name}
aliases = {'action_settings':'settings','title_settings':'settings','action_wakeup':'wake_play','action_connect_immediately':'setup','action_register':'register_console','action_add_manual':'manual_ip','title_regist':'register_console','action_regist':'register_console','title_edit_manual':'manual_ip','preferences_category_title_general':'settings','preferences_category_title_stream':'video','preferences_category_title_export':'data','preferences_registered_hosts_title':'your_consoles','registered_hosts_empty_info':'empty_title','display_hosts_empty_discovery_off_info':'empty_intro','display_hosts_empty_discovery_on_info':'searching'}
def xmltext(value):
    return html.escape(value, quote=False).replace("'", "\\'").replace('"', '\\"').replace('\n', '\\n')
for code,name in LANGUAGES.items():
    catalog=json.loads((ROOT/f'localization/{code}.json').read_text())
    assert set(catalog)==set(base), f'{code}: catalog keys do not match English'
    assert all(isinstance(v,str) and v.strip() for v in catalog.values()),code
    for key in base:
        assert re.findall(r'%\d*\$?[sd]',base[key]) == re.findall(r'%\d*\$?[sd]',catalog[key]),(code,key)
    # Shared copy is authored per language; additional native copy is a translation draft.
    native={f'dv_{key}':texts.get(code,texts['en']) for key,texts in extra.items()} if code in ('en','ru') else {}
    android_catalog=ROOT/f'localization/android/{code}.json'
    if android_catalog.exists():
        android_base=json.loads((ROOT/'localization/android/en.json').read_text())
        android_strings=json.loads(android_catalog.read_text())
        assert set(android_strings)==set(android_base), f'{code}: incomplete Android catalog'
        for key,value in android_base.items():
            assert sorted(re.findall(r'%(?:\d+\$)?[sd]',value)) == sorted(re.findall(r'%(?:\d+\$)?[sd]',android_strings[key])), (code,key)
        native.update(android_strings)
    for key,texts in extra.items():
        if code in texts:native['dv_'+key]=texts[code]
        elif 'dv_'+key not in native:native['dv_'+key]=texts['en']
    native.update({f'dv_{key}':value for key,value in catalog.items()})
    version=re.search(r'versionName\s+"([^"]+)"',(ROOT/'android/app/build.gradle').read_text()).group(1)
    native['dv_setup_credit']=extra['source_exact'].get(code,extra['source_exact']['en']).replace('%1$s','https://github.com/remteh-by/remteh-remote-play/releases/tag/v'+version)
    native.update({key:catalog[value].rstrip(' · ') if key=='preferences_registered_hosts_title' else catalog[value] for key,value in aliases.items()})
    qualifier={'id':'in','zh':'zh-rCN'}.get(code,code)
    directory=ROOT/'android/app/src/main/res'/('values' if code=='en' else f'values-{qualifier}')
    directory.mkdir(exist_ok=True)
    # Existing English aliases already live in strings.xml; other languages override them.
    native={k:v for k,v in native.items() if k in used}
    if code=='en': native={k:v for k,v in native.items() if k.startswith('dv_')}
    (directory/'deckivo_strings.xml').write_text('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate-localizations.py; edit localization/*.json. -->\n<resources>\n'+''.join(f'    <string name="{key}">{xmltext(value)}</string>\n' for key,value in sorted(native.items()))+'</resources>\n')
    all_catalogs[code]=catalog
(ROOT/'android/app/src/main/res/xml/locales_config.xml').write_text('<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n'+''.join(f'    <locale android:name="{"in" if code=="id" else code}" />\n' for code in LANGUAGES)+'</locale-config>\n')
print(f'{len(LANGUAGES)} languages × {len(base)} shared keys validated and generated.')
